#!/usr/bin/env bash

# =====================================================================
# СЦЕНАРИЙ ЛОКАЛЬНОГО ТЕСТИРОВАНИЯ ЭКОСИСТЕМЫ (БЕЗ ЖИВОГО TELEGRAM API)
# ФАЙЛ: test-telegram-e2e.sh
# =====================================================================

# Выходим сразу при возникновении ошибок
set -e

# Конфигурация локального окружения
APP_URL="http://localhost:8080/telegram"
MOCK_CHAT_ID="77712345"
MOCK_USER_NAME="Natalia"

echo "================================================================="
# CHECK: Убедитесь, что ваше Java-приложение запущено на порту 8080,
# а в локальном Ollama активна модель Llama3 (команда: ollama run llama3)
echo "🚀 Запуск сквозной симуляции диалога для Chat ID: ${MOCK_CHAT_ID}"
echo "================================================================="

# -----------------------------------------------------------------
# ТУР 1: Первичное обращение клиента и нечеткий поиск услуги
# -----------------------------------------------------------------
echo -e "\n[Тур 1] Отправка сообщения: 'Привет! Хочу записаться на стрижку'..."

curl -X POST "${APP_URL}" \
  -H "Content-Type: application/json" \
  -H "X-Mock-Trace-Id: TRACE-CURL-001" \
  -d "{
    \"message\": {
      \"chat\": {
        \"id\": ${MOCK_CHAT_ID}
      },
      \"from\": {
        \"firstName\": \"${MOCK_USER_NAME}\"
      },
      \"text\": \"Привет! Хочу записаться на стрижку\"
    }
  }"

echo -e "\n\n💡 Ожидаемое поведение в логах приложения:"
echo "1. Network Boundary зафиксирует входящий вебхук."
echo "2. BookingServiceImpl автоматически зарегистрирует профиль '${MOCK_USER_NAME}' в таблице CLIENTS."
echo "3. В таблице MESSAGE_TRACES появится запись лога INBOUND."
echo "4. LangChain4j вызовет ИИ-инструмент searchServices(\"стрижка\") и вернет список подходящих позиций."

# Даем время на когнитивное осмысление локальной LLM перед следующим шагом
echo -e "\n⏳ Пауза 3 секунды для завершения генерации ответа моделью Llama3..."
sleep 3

# -----------------------------------------------------------------
# ТУР 2: Финальное согласование мастера, даты и времени
# -----------------------------------------------------------------
echo -e "\n[Тур 2] Отправка сообщения: 'Запиши к Елене на 25 августа в 14:30'..."

curl -X POST "${APP_URL}" \
  -H "Content-Type: application/json" \
  -H "X-Mock-Trace-Id: TRACE-CURL-002" \
  -d "{
    \"message\": {
      \"chat\": {
        \"id\": ${MOCK_CHAT_ID}
      },
      \"from\": {
        \"firstName\": \"${MOCK_USER_NAME}\"
      },
      \"text\": \"Запиши к Елене на 25 августа в 14:30\"
    }
  }"

echo -e "\n\n💡 Ожидаемое поведение в логах приложения:"
echo "1. ИИ-движок извлечет историю из MessageWindowChatMemory для этого пользователя."
echo "2. На основе системного промпта модель преобразует дату в ISO-формат '2026-08-25T14:30'."
echo "3. ИИ вызовет bookAppointmentSlot по строковым бизнес-ключам."
echo "4. В таблице APPOINTMENTS запишется строка со статусом AI_PENDING и уникальным ticketCode (например, SB-260825-XXXXX)."
echo "================================================================="
echo "✅ Симуляция успешно завершена. Проверьте консоль бэкенда и базу H2!"
