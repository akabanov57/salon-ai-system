package salon.api.service;

import salon.api.model.PlatformType;

/**
 * <h2>Сервис ведения истории переписки с клиентами салона</h2>
 * Данный компонент отвечает за надежное сохранение каждого шага диалога между клиентом
 * и салоном красоты (будь то сообщения от клиента или ответы нашего ИИ-помощника).
 *
 * <p><b>БИЗНЕС-ЦЕННОСТЬ:</b>
 * <ul>
 *   <li><b>Анализ конфликтных ситуаций:</b> Если клиент утверждает, что просил запись на 14:00,
 *       а система забронировала 16:00, история переписки покажет точный первоначальный текст.</li>
 *   <li><b>Обучение ИИ-ассистента:</b> Позволяет владельцу салона просматривать логи диалогов,
 *       чтобы вовремя замечать ошибки ИИ и корректировать его инструкции.</li>
 *   <li><b>Контекст для мастеров:</b> Дает возможность увидеть, какие пожелания клиент высказывал
 *       в чате перед визитом (например, "хочу сложное окрашивание у Елены").</li>
 * </ul>
 * </p>
 */
public interface MessageTraceService {
  /**
   * Направление движения сообщения в процессе диалога.
   */
  enum Direction {
    /** Сообщение пришло ОТ клиента в салон (входящее). */
    INBOUND,

    /** Ответ отправлен ИЗ салона клиенту (исходящий от ИИ или администратора). */
    OUTBOUND
  }

  /**
   * Сохраняет запись разговора в архивную базу данных салона [2].
   *
   * @param traceId      Сквозной технический маркер операции для отслеживания пути запроса [2].
   * @param platformType Канал связи, через который общается клиент (TELEGRAM, INSTAGRAM) [2].
   * @param platformId   Натуральный идентификатор пользователя внутри мессенджера (например, Telegram User ID) [2].
   * @param direction    Кто отправил сообщение: клиент (INBOUND) или салон (OUTBOUND) [2].
   * @param rawPayload   Полный исходный технический пакет данных (JSON) от мессенджера [2].
   * @param messageText  Чистый, читаемый текст сообщения [2].
   */
  void logTrace(String traceId, PlatformType platformType, String platformId, Direction direction, String rawPayload, String messageText);

}
