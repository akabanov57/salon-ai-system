package salon.api.service;

/**
 * <h3>Доменный контракт диспетчеризации статусов визитов (Сценарий 4)</h3>
 *
 * <p>Управляет жизненным циклом записей клиентов, обеспечивая строгое соблюдение
 * правил конечного автомата (State Machine) на переходы между статусами визитов [Strict
 * Grounding].</p>
 *
 * <p><b>Разрешенная матрица переходов:</b>
 * <ul>
 *   <li>{@code AI_PENDING} (Черновик ИИ) &rarr; {@code APPROVED} (Одобрено управляющим) или
 *   {@code CANCELED} (Отменено)</li>
 *   <li>{@code APPROVED} (Одобрено) &rarr; {@code COMPLETED} (Успешно визит состоялся) или
 *   {@code CANCELED} (Отменено)</li>
 *   <li>{@code CANCELED}, {@code COMPLETED} &rarr; Являются терминальными статусами, любые
 *   переходы из них запрещены</li>
 * </ul>
 * </p>
 */
public interface AppointmentWorkflowService {

  /**
   * Переводит предварительный черновик записи в официальный статус APPROVED (Одобрение управляющим).
   *
   * <p><b>Бизнес-контекст:</b> Управляющий салоном просматривает входящую сетку предварительных ИИ-броней
   * в Vaadin UI и подтверждает визит одной кнопкой. Данная операция делает запись официальной [Strict Grounding].</p>
   *
   * @param ticketCode Публичный строковый код билета визита, сгенерированный сервером (например, 'SB-20260813-A7X').
   *                   Не может быть пустым или состоять из пробелов.
   * @throws IntegrityViolationException если запись с указанным кодом билета не обнаружена в системе,
   *                                      либо если текущий статус записи не позволяет выполнить переход в APPROVED
   *                                      (например, запись уже была отменена клиентом в чате) [Strict Grounding].
   * @throws StorageInfrastructureException если произошел непредвиденный сбой инфраструктуры СУБД
   *                                         (потеря соединения, таймаут пула подключений) [Strict Grounding].
   */
  void approveAppointment(String ticketCode);

  /**
   * Переводит запись в терминальный статус CANCELED (Отмена визита).
   *
   * <p><b>Бизнес-контекст:</b> Допускается отмена как предварительных черновиков ИИ ({@code AI_PENDING}),
   * так и уже одобренных управляющим сеансов ({@code APPROVED}). Отмена полностью освобождает временной
   * интервал мастера и делает его доступным для последующего ИИ-бронирования другими клиентами [Strict Grounding].</p>
   *
   * @param ticketCode Публичный строковый код билета визита, сгенерированный сервером (например, 'SB-20260813-A7X').
   *                   Не может быть пустым или состоять из пробелов.
   * @throws IntegrityViolationException если запись не найдена, либо находится в терминальном состоянии {@code COMPLETED}
   *                                      (нельзя отменить визит, который уже успешно состоялся в прошлом) [Strict Grounding].
   * @throws StorageInfrastructureException если произошел критический сбой на уровне персистентного хранения данных [Strict Grounding].
   */
  void cancelAppointment(String ticketCode);

  /**
   * Переводит одобренную запись в терминальный статус COMPLETED (Фиксация успешного обслуживания).
   *
   * <p><b>Бизнес-контекст:</b> Вызывается в конце сеанса или рабочего дня, подтверждая, что процедура
   * была успешно оказана клиенту. Данный статус закрывает сделку в финансовом контуре и открывает для
   * ИИ-движка возможность запуска последующих сценариев сбора отзывов и удержания гостей [Strict Grounding].</p>
   *
   * @param ticketCode Публичный строковый код билета визита, сгенерированный сервером (например, 'SB-20260813-A7X').
   *                   Не может быть пустым или состоять из пробелов.
   * @throws IntegrityViolationException если запись не найдена, либо если совершается нелегальный прыжок статуса
   *                                      в обход ручного одобрения человеком (например, попытка завершить черновик
   *                                      напрямую из {@code AI_PENDING}) [Strict Grounding].
   * @throws StorageInfrastructureException если произошел критический сбой на уровне инфраструктуры хранения [Strict Grounding].
   */
  void completeAppointment(String ticketCode);
}
