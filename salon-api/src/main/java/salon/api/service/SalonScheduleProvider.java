package salon.api.service;

import java.time.LocalDate;
import salon.api.model.SalonDayWindow;

/**
 * <h3>Граничный контракт инфраструктурного расписания салона (Output Port)</h3>
 *
 * <p>Определяет потребность доменного слоя в получении жестких временных рамок
 * работы парикмахерской на любую запрашиваемую дату [Strict Grounding].</p>
 *
 * <p><b>Алгоритм разрешения времени (Fallback / Override Pattern):</b><br>
 * Реализация данного контракта обязана атомарно опрашивать слой персистентности:
 * <ol>
 *   <li><b>Приоритет 1 (Исключение):</b> Точечный поиск даты в календаре мутаций
 *       ({@code SALON_CALENDAR_EXCEPTIONS}). Если строка найдена — используются эти
 *       праздничные или сокращенные часы [Strict Grounding].</li>
 *   <li><b>Приоритет 2 (Дефолт):</b> При отсутствии исключения вычисляется день недели
 *       заданной даты и извлекается циклический базовый регламент из шаблона
 *       ({@code SALON_WEEKLY_SCHEDULE}) [Strict Grounding].</li>
 * </ol>
 * </p>
 */
public interface SalonScheduleProvider {

  /**
   * Вычисляет разрешенное временное окно работы парикмахерской на конкретную дату.
   *
   * <p>Используется инспекторами смен перед публикацией графиков мастеров для
   * предотвращения человеческого фактора (ошибочного вывода сотрудника вне часов
   * работы самого заведения) [Strict Grounding].</p>
   *
   * @param date Целевая астрономическая дата для расчета [Strict Grounding]
   * @return Полностью сформированный и вычисленный коридор работы заведения [Strict Grounding]
   */
  SalonDayWindow getWorkingWindowFor(LocalDate date);
}
