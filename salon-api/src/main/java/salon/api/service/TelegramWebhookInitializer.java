package salon.api.service;

public interface TelegramWebhookInitializer {

  /**
   * <h3>Инициализатор вебхуков Telegram (Способ Б)</h3>
   *
   * <p>Решает проблему блокировки потока старта приложения. Компонент использует аннотацию
   * "@Prototype", благодаря чему созданный экземпляр утилитарного класса может быть очищен
   * сборщиком мусора (GC) сразу после выполнения процедуры регистрации вебхука [Strict
   * Grounding].</p>
   *
   * <p><b>Архитектурное обоснование жизненного цикла вебхука (Почему исключен метод deleteWebhook
   * при остановке):</b>
   * Удаление регистрации вебхука на этапе остановки (shutdown) приложения умышленно не реализуется
   * по следующим соображениям:
   * <ul>
   *   <li><b>Сохранение очереди сообщений (Message Queueing):</b> Если сервер временно останавливается для
   *   обновления или перезапуска, серверы Telegram продолжают принимать сообщения от пользователей и накапливать их.
   *   Фиксируя временную недоступность нашего эндпоинта (HTTP-ошибки серии 5xx или таймауты подключения), Telegram
   *   автоматически кэширует входящий трафик и запускает политику повторных попыток доставки (retry policy)
   *   с увеличивающимся интервалом. Как только приложение запускается снова, оно получает из накопившейся очереди
   *   все сообщения, отправленные во время простоя. Если же вызвать метод {@code deleteWebhook}, Telegram мгновенно сотрет
   *   регистрацию, и новые сообщения пользователей в этот период будут полностью проигнорированы или отклонены.</li>
   *   <li><b>Исключение избыточных сетевых запросов (Unnecessary Network Roundtrips):</b> Удаление вебхука при
   *   каждой плановой остановке JVM и его повторная регистрация при старте создают лишние транзитивные запросы к API Telegram,
   *   негативно влияя на общее время развертывания (deployment) и завершения процессов системы.</li>
   * </ul>
   * Вызов удаления вебхука оправдан исключительно при полной декоммиссии бота или при динамическом переключении
   * режима получения сообщений на Long Polling в рантайме.</p>
   */
  void registerWebhook();
}
