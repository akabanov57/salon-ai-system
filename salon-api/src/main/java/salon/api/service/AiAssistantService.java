package salon.api.service;

import salon.api.model.ProcessMessageCommand;

/**
 * <h2>Центральный интерфейс ИИ-ассистента салона красоты (Core AI Orchestrator)</h2>
 * <p>
 * Данный сервис является главным аналитическим и когнитивным центром приложения.
 * Он выступает в роли "виртуального администратора" салона, который интерпретирует
 * неструктурированные текстовые запросы клиентов (естественный язык) и превращает их
 * в конкретные бизнес-намерения: запись на стрижку, перенос визита или консультацию по услугам.
 * </p>
 *
 * <h3>Бизнес-ценность для салона красоты:</h3>
 * <ul>
 *   <li><b>Автоматизация записи 24/7:</b> Снижает нагрузку на живых администраторов,
 *       мгновенно обрабатывая ночные и пиковые потоки входящих сообщений.</li>
 *   <li><b>Интеллектуальный анализ контекста (Intent Recognition):</b> Распознает сложные
 *       разговорные формулировки клиентов (например, <i>"хочу к Елене на сложное окрашивание,
 *       как в прошлый раз"</i>) и сопоставляет их с реальной матрицей мастеров и расписанием в СУБД.</li>
 *   <li><b>Удержание клиентов (Instant UX Response):</b> Исключает задержки в ответах,
 *       увеличивая конверсию из обычного вопроса в мессенджере в подтвержденную запись на визит.</li>
 * </ul>
 *
 * @see ProcessMessageCommand
 * @see AiEngineException
 */
public interface AiAssistantService {

  /**
   * <h3>Синтез интеллектуального ответа на обращение клиента</h3>
   * <p>
   * Метод принимает очищенную доменную команду, извлекает текст сообщения пользователя,
   * восстанавливает историю предыдущих диалогов с этим клиентом (Chat Memory) и запускает
   * генерацию оптимального ответа через подключенную Большую Языковую Модель (LLM).
   * </p>
   *
   * <h4>Архитектурные и рантайм-гарантии (SLA):</h4>
   * <ul>
   *   <li><b>Изоляция потоков выполнения:</b> Реализации этого метода обязаны изолировать
   *       тяжелые сетевые запросы к нейросети во внешних пулах потоков, предотвращая
   *       блокировку основных рабочих ресурсов веб-сервера.</li>
   *   <li><b>Защита от зависаний (Strict Timeout Guard):</b> Метод гарантирует принудительное
   *       прерывание операции, если генерация ответа занимает больше установленного времени
   *       (например, при временном падении Ollama или задержках API OpenAI).</li>
   * </ul>
   *
   * @param command Валидная доменная команда, инкапсулирующая все необходимые
   *                бизнес-параметры и идентификаторы текущей транзакции диалога.
   * @return Чистый текстовый ответ, сформированный нейросетью для отправки на экран мобильного телефона клиента.
   * @throws AiEngineException Если нейросетевое ядро дало технический сбой, превышен таймаут ожидания
   *                            или фреймворк LangChain4j не смог синтезировать контекст ответа.
   */
  String processChat(ProcessMessageCommand command);
}
